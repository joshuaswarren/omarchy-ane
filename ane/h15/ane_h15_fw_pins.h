/* Image identity only; this does not select resources or qualify an engine. */
static inline const struct ane_h15_fw *
ane_h15_fw_for_engine(unsigned int soc, unsigned int engine)
{
	if (soc == 0x6032) {
		if (engine == 0)
			return &ane_fw_t6031;
		if (engine == 1)
			return &ane_fw_t6032_ane1;
		return 0;
	}
	if (engine)
		return 0;
	switch (soc) {
	case 0x8122:
		return &ane_fw_t8122;
	case 0x6030:
		return &ane_fw_t6030;
	case 0x6031:
	case 0x6034:
		return &ane_fw_t6031;
	default:
		return 0;
	}
}

