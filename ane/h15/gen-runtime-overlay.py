#!/usr/bin/env python3
"""Derive each ane_h15 run-time overlay and write ane_h15_overlay_data.h.

The boot-time overlays mint a label on an existing node with an empty fragment such as
    fragment@1 { target-path = "/soc/.../power-controller@520"; ps_ane_sys: __overlay__ { }; };
and then refer to that label. A boot-time merge gives the target node the label's phandle. The kernel's run-time overlay code does
NOT: it skips the phandle of an overlay node merged into an existing node, so a reference to it points at nothing.

So this script removes only those empty label-minting fragments. The labels they minted become external references, which dtc -@
records as __fixups__, and the kernel resolves them from /__symbols__. Everything else in the overlay is kept byte for byte. The
label -> path table is written next to the blob so the module can publish exactly those labels (ane_h15_overlay.c).

usage: gen-runtime-overlay.py [--check]     (--check: fail if ane_h15_overlay_data.h is not what this would write)
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOCS = {
    "t8122": {"src": "t8122-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys"]},
    "t6030": {"src": "t6030-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys"]},
    "t6031": {"src": "t6031-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys", "ps_ane_mpm", "ps_ane_cpu", "ps_ane_td", "ps_ane_base"]},
}
EMPTY_FRAGMENT = re.compile(r'\tfragment@(\d+) \{\n\t\ttarget-path = "([^"]+)";\n\t\t(\w+): __overlay__ \{\n\t\t\};\n\t\};\n\n?')


def t8122_runtime_patch(text):
    """The run-time variant is applied to a LIVE kernel: an apple,t8110-dart
    node with status okay is probed by the running apple-dart driver the
    moment the overlay merges, on real ANE DART MMIO - the enabled-DART hang
    documented at boot on T6030 (PR 173), reproduced on a J613 lab machine
    2026-11-09. The apply_overlay contract for T8122 is disabled DARTs and
    no IOMMU client, so the run-time variant keeps the three instances
    disabled and drops the ane node's iommus. The boot-time overlay is
    unchanged."""
    for pa in ("311800000", "311810000", "311820000"):
        start = text.index(f"iommu@{pa}")
        ok = text.index('status = "okay"', start)
        text = text[:ok] + 'status = "disabled"' + text[ok + len('status = "okay"'):]
    return re.sub(r"\n\t\t\t\tiommus = <&ane_dart0 0>, <&ane_dart1 0>, <&ane_dart2 0>;", "", text)


def derive(soc):
    """Return (runtime dts text, [(label, path)]) for one SoC."""
    text = (HERE / SOCS[soc]["src"]).read_text()
    found = [(m.group(3), m.group(2)) for m in EMPTY_FRAGMENT.finditer(text)]
    if [label for label, _ in found] != SOCS[soc]["labels"]:
        raise SystemExit(f"{soc}: label-minting fragments are {[l for l, _ in found]}, expected {SOCS[soc]['labels']}")
    text = EMPTY_FRAGMENT.sub("", text)
    if soc == "t8122":
        text = t8122_runtime_patch(text)
    return text, found


def compile_blob(dts_text):
    with tempfile.TemporaryDirectory() as tmp:
        src, out = Path(tmp) / "o.dts", Path(tmp) / "o.dtbo"
        src.write_text(dts_text)
        run = subprocess.run(["dtc", "-@", "-I", "dts", "-O", "dtb", "-o", str(out), str(src)], capture_output=True, text=True, check=False)
        if run.returncode:
            raise SystemExit(f"dtc failed: {run.stderr}")
        return out.read_bytes()


def render():
    lines = ["/* SPDX-License-Identifier: GPL-2.0-only OR MIT */",
             "/* GENERATED by gen-runtime-overlay.py from the per-SoC boot-time overlays. Do not edit; run the script. */",
             "#ifndef __ANE_H15_OVERLAY_DATA_H__", "#define __ANE_H15_OVERLAY_DATA_H__", ""]
    for soc in SOCS:
        dts, syms = derive(soc)
        blob = compile_blob(dts)
        lines.append(f"static const u8 ane_h15_ovl_{soc}_blob[] = {{")
        for i in range(0, len(blob), 12):
            lines.append("\t" + ", ".join(f"0x{b:02x}" for b in blob[i:i + 12]) + ",")
        lines += ["};", "", f"static const struct ane_h15_ovl_sym ane_h15_ovl_{soc}_syms[] = {{"]
        lines += [f'\t{{ "{label}", "{path}" }},' for label, path in syms]
        lines += ["};", ""]
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv):
    out = HERE / "ane_h15_overlay_data.h"
    text = render()
    if argv[1:] == ["--check"]:
        return 0 if out.exists() and out.read_text() == text else 1
    out.write_text(text)
    print("wrote", out, len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
