#!/usr/bin/env python3
"""Derive each ane_h15 run-time overlay and write ane_h15_overlay_data.h.

The boot-time overlays mint a label on an existing node with an empty fragment such as
    fragment@1 { target-path = "/soc/.../power-controller@520"; ps_ane_sys: __overlay__ { }; };
and then refer to that label. A boot-time merge gives the target node the label's phandle. The kernel's run-time overlay code does
NOT: it skips the phandle of an overlay node merged into an existing node, so a reference to it points at nothing.

So this script removes only those empty label-minting fragments. The labels they minted become external references, which dtc -@
records as __fixups__, and the kernel resolves them from /__symbols__. Everything else in the overlay is kept byte for byte. The
label -> path table is written next to the blob so the module can publish exactly those labels (ane_h15_overlay.c).

usage: gen-runtime-overlay.py [--check]     (--check: fail if ane_h15_overlay_data.h is not what this would write)
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOCS = {
    "t8122": {"src": "t8122-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys"]},
    "t6030": {"src": "t6030-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys"]},
    "t6031": {"src": "t6031-ane-dart-experimental.dts", "labels": ["aic", "ps_ane_sys", "ps_ane_mpm", "ps_ane_cpu", "ps_ane_td", "ps_ane_base"]},
}
EMPTY_FRAGMENT = re.compile(r'\tfragment@(\d+) \{\n\t\ttarget-path = "([^"]+)";\n\t\t(\w+): __overlay__ \{\n\t\t\};\n\t\};\n\n?')


def runtime_dart_disable(text):
    """The run-time variant is applied to a LIVE kernel: an apple,t8110-dart
    (or t6031) node with status okay is probed by the running apple-dart
    driver the moment the overlay merges, on real ANE DART MMIO - the
    enabled-DART hang documented at boot on T6030 (PR 173), reproduced at
    overlay-apply time on a J613 lab machine 2026-11-09. The run-time
    variant therefore keeps every ANE DART instance disabled and drops the
    ane node's iommus (no IOMMU client), for every SoC, per the apply_overlay
    contract. The boot-time overlays are unchanged; stage=5 map_fw on the
    run-time path needs a boot-time overlay or an explicit later decision,
    since a live stream requires the DART driver bound."""
    text = re.sub(r'(iommu@[0-9a-f]+ \{(?:(?!};).)*?)status = "okay"',
                  r'\1status = "disabled"', text, flags=re.DOTALL)
    return re.sub(r"\n\t+iommus = <&ane_dart0 0>, <&ane_dart1 0>, <&ane_dart2 0>;", "", text)


def derive(soc, boot=False):
    """Return (overlay dts text, [(label, path)]) for one SoC. boot=True keeps
    the DART instances enabled and the ane node's iommus: the boot-time
    variant the stage=3 boot path applies BEFORE the driver probes, so the
    DARTs bind while the tree is still cold. Only the label-minting empty
    fragments are removed either way."""
    text = (HERE / SOCS[soc]["src"]).read_text()
    found = [(m.group(3), m.group(2)) for m in EMPTY_FRAGMENT.finditer(text)]
    if [label for label, _ in found] != SOCS[soc]["labels"]:
        raise SystemExit(f"{soc}: label-minting fragments are {[l for l, _ in found]}, expected {SOCS[soc]['labels']}")
    stripped = EMPTY_FRAGMENT.sub("", text)
    return (stripped if boot else runtime_dart_disable(stripped)), found


def check_variant(soc, text, boot):
    """Structural check per variant: the runtime blob must carry zero enabled
    DARTs and no ane iommus (PR 382 contract), the boot blob must carry the
    three enabled instances and the iommus (w91 M6 lesson: all instances or
    DMA never completes)."""
    ane = re.search(r'ane: ane@[0-9a-f]+ \{(?:(?!\n\t\t\};).)*', text, flags=re.DOTALL).group(0)
    darts = re.findall(r'ane_dart[0-9]+: iommu@[0-9a-f]+ \{(?:(?!};).)*status = "(\w+)"', text, flags=re.DOTALL)
    has_iommus = "iommus = <&ane_dart0 0>, <&ane_dart1 0>, <&ane_dart2 0>;" in ane
    enabled = darts.count("okay")
    if not boot and (enabled or has_iommus):
        raise SystemExit(f"{soc}: runtime variant must have 0 enabled DARTs and no ane iommus (got {enabled} enabled)")
    if boot and (enabled != 3 or not has_iommus):
        raise SystemExit(f"{soc}: boot variant must have 3 enabled DARTs and the ane iommus (got {enabled} enabled, iommus={has_iommus})")


def compile_blob(dts_text):
    with tempfile.TemporaryDirectory() as tmp:
        src, out = Path(tmp) / "o.dts", Path(tmp) / "o.dtbo"
        src.write_text(dts_text)
        run = subprocess.run(["dtc", "-@", "-I", "dts", "-O", "dtb", "-o", str(out), str(src)], capture_output=True, text=True, check=False)
        if run.returncode:
            raise SystemExit(f"dtc failed: {run.stderr}")
        return out.read_bytes()


def render():
    lines = ["/* SPDX-License-Identifier: GPL-2.0-only OR MIT */",
             "/* GENERATED by gen-runtime-overlay.py from the per-SoC boot-time overlays. Do not edit; run the script. */",
             "#ifndef __ANE_H15_OVERLAY_DATA_H__", "#define __ANE_H15_OVERLAY_DATA_H__", ""]
    for soc in SOCS:
        dts, syms = derive(soc)
        check_variant(soc, dts, boot=False)
        blob = compile_blob(dts)
        bdts, _ = derive(soc, boot=True)
        check_variant(soc, bdts, boot=True)
        bblob = compile_blob(bdts)
        lines.append(f"static const u8 ane_h15_ovl_{soc}_blob[] = {{")
        for i in range(0, len(blob), 12):
            lines.append("\t" + ", ".join(f"0x{b:02x}" for b in blob[i:i + 12]) + ",")
        lines += ["};", "", f"static const u8 ane_h15_ovl_{soc}_boot_blob[] = {{"]
        for i in range(0, len(bblob), 12):
            lines.append("\t" + ", ".join(f"0x{b:02x}" for b in bblob[i:i + 12]) + ",")
        lines += ["};", "", f"static const struct ane_h15_ovl_sym ane_h15_ovl_{soc}_syms[] = {{"]
        lines += [f'\t{{ "{label}", "{path}" }},' for label, path in syms]
        lines += ["};", ""]
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv):
    out = HERE / "ane_h15_overlay_data.h"
    text = render()
    if argv[1:] == ["--check"]:
        return 0 if out.exists() and out.read_text() == text else 1
    out.write_text(text)
    print("wrote", out, len(text), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
